#!/usr/bin/env python3
"""Idempotent patches for the DBY-W09 4.19.157 vendor kernel tree.

Run after extracting the official tarball:
    python3 scripts/patch_source.py [SRC=kernel]
"""
import os, sys

K = sys.argv[1] if len(sys.argv) > 1 else 'src/kernel'

def sub(path, old, new, label):
    p = os.path.join(K, path)
    s = open(p, encoding='utf-8', errors='surrogateescape').read()
    if new in s:
        print(f'  [skip] {label}')
        return
    if old not in s:
        print(f'  [MISS] {label} ({path})')
        return
    open(p, 'w', encoding='utf-8', errors='surrogateescape').write(s.replace(old, new, 1))
    print(f'  [ok]   {label}')

print('patching', K)
# clang prints several " version " lines; mkcompile_h must take the first
sub('scripts/mkcompile_h',
    "CC_VERSION=$($CC -v 2>&1 | grep ' version ' | sed 's/[[:space:]]*$//')",
    "CC_VERSION=$($CC -v 2>&1 | grep ' version ' | head -n1 | sed 's/[[:space:]]*$//')",
    'mkcompile_h: single-line clang version')
# out-of-tree (O=) builds need srctree-absolute qcacld paths
sub('drivers/qcacld/Kbuild', 'WLAN_ROOT := drivers/qcacld',
    'WLAN_ROOT := $(srctree)/drivers/qcacld', 'qcacld: WLAN_ROOT')
sub('drivers/qcacld/Kbuild', 'WLAN_COMMON_INC := qca-cmn',
    'WLAN_COMMON_INC := $(srctree)/drivers/qca-wifi-host-cmn', 'qcacld: WLAN_COMMON_INC')
# Huawei gated kprobes behind HUAWEI_KERNEL_DEBUG; the stock device kernel has
# KPROBES=y with HUAWEI_KERNEL_DEBUG=n, so drop the extra dependency.
sub('arch/Kconfig', '\tdepends on HAVE_KPROBES && HUAWEI_KERNEL_DEBUG\n',
    '\tdepends on HAVE_KPROBES\n', 'arch/Kconfig: KPROBES dependency')
sub('arch/Kconfig', '\tdepends on KPROBES && HAVE_KRETPROBES && HUAWEI_KERNEL_DEBUG\n',
    '\tdepends on KPROBES && HAVE_KRETPROBES\n', 'arch/Kconfig: KRETPROBES dependency')
# These -Werror= promotions are 5.x-era backports; 4.19 vendor code (mm/vmalloc.c
# etc.) is not clean for them. Keep them as plain warnings.
for flag in ['-Werror=implicit-int', '-Werror=strict-prototypes', '-Werror=date-time',
             '-Werror=incompatible-pointer-types', '-Werror=designated-init']:
    sub('Makefile', f'KBUILD_CFLAGS   += $(call cc-option,{flag})\n',
        f'# DBY-W09: keep 4.19 behaviour, do not promote warning to error\n'
        f'# KBUILD_CFLAGS   += $(call cc-option,{flag})\n', f'Makefile: {flag}')

# lcd_kit_dpd.h is generated by Huawei's lcd_kit_parser.pl from vendor XML
# configs that are not part of the opensource package. DPD mode is inactive
# unless "lcd_dpd" is on the cmdline, so an empty mapping is behaviour-neutral.
STUB = """/* DBY-W09: generated by Huawei's lcd_kit_parser.pl from vendor XML configs
 * which are not shipped in the opensource package. DPD is inactive unless
 * "lcd_dpd" is on the cmdline, so an empty mapping is behaviour-neutral. */
#ifndef _LCDKIT_DPD__H_
#define _LCDKIT_DPD__H_
struct lcd_kit_xml_string_name_map {
\tchar *xml_string_name;
\tchar *dtsi_string_name;
};
static struct lcd_kit_xml_string_name_map xml_string_name_map[] = {
\t{ "", "" },
};
#endif
"""
for d in ('drivers/devkit/lcdkit/lcdkit3.0/kernel/qcom/common/src',
          'drivers/devkit/lcdkit/lcdkit3.0/kernel/common/src'):
    f = os.path.join(K, d, 'lcd_kit_dpd.h')
    if os.path.exists(f):
        print(f'  [skip] lcd_kit_dpd.h stub ({d})')
    else:
        open(f, 'w').write(STUB)
        print(f'  [ok]   lcd_kit_dpd.h stub ({d})')

# RELOCATABLE is a hidden symbol only selected by RANDOMIZE_BASE. The running
# kernel runs without KASLR, and a non-relocatable link puts .bss.rtic out of
# ADR_PREL_PG_HI21 range with binutils 2.38, so make PIE the default (KASLR
# itself stays disabled).
# Keep RELOCATABLE=n (running kernel has KASLR off) but make sure the hidden
# symbol keeps its upstream 'bool' type.
sub('arch/arm64/Kconfig',
    'config RELOCATABLE\n\tdef_bool y\n\tselect ARCH_HAS_RELR\n',
    'config RELOCATABLE\n\tbool\n\tselect ARCH_HAS_RELR\n',
    'arch/arm64/Kconfig: RELOCATABLE back to bool')

# Huawei appends a second ".bss" with RTIC data AFTER STABS_DEBUG. Because the
# ".comment 0" output section resets the location counter, that .bss lands at
# 0x1000, i.e. >4GB away from a non-relocatable kernel's _text; binutils then
# fails with R_AARCH64_ADR_PREL_PG_HI21. Fold the RTIC data into the real .bss
# (also puts it inside __bss_start..__bss_stop so it gets zeroed).
sub('include/asm-generic/vmlinux.lds.h',
    '\t\t*(COMMON)\t\t\t\t\t\t\\\n',
    '\t\t*(COMMON)\t\t\t\t\t\t\\\n\t\tKEEP(*(.bss.rtic))\t\t\t\\\n',
    'generic lds: fold .bss.rtic into BSS')
sub('arch/arm64/kernel/vmlinux.lds.S',
    '\n\t.bss : {\t\t\t/* bss segment\t\t*/\n         RTIC_BSS\n\t}\n',
    '\n', 'arm64 lds: drop trailing .bss(rtIC) block')
